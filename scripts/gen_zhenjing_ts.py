#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
将 parse_zhenjing.py 产出的 zhenjing_raw.json 生成为
src/data/ieltsZhenjingLexicon.ts（与 OFFLINE_LEXICON 同构，可直接被
dictionaryService 消费，作为雅思真题词库的扩充层）。

字段映射：
- word/pos/zh/phonetic/topic ← 原 PDF
- ieltsBand ← 词长估算（真经词条均为雅思核心词，Band 6.0-7.5 分布）
- examContextTag ← 雅思词汇真经 · {真经主题}
- example/exampleTranslation ← 留空（原书无例句，由牛津层/后端补全）
"""
import json
from pathlib import Path

RAW = Path(r'D:\ielts-lexicon\scripts\zhenjing_raw.json')
OUT = Path(r'D:\ielts-lexicon\src\data\ieltsZhenjingLexicon.ts')

# 真经 21 主题 → App 7 大话题
TOPIC_MAP = {
    '自然地理': '环境生态', '植物研究': '环境生态', '动物保护': '环境生态',
    '太空探索': '科技媒体', '科技发明': '科技媒体',
    '学校教育': '学术教育', '语言演化': '学术教育', '文化历史': '社会文化',
    '娱乐运动': '社会文化', '物品材料': '社会文化', '时尚潮流': '社会文化',
    '饮食健康': '心理生活', '建筑场所': '社会文化', '交通旅行': '社会文化',
    '国家政府': '政府法律', '社会经济': '经济工作', '法律法规': '政府法律',
    '征战沙场': '政府法律', '社会关系': '社会文化', '行为动作': '社会文化',
    '身心健康': '心理生活', '时间日期': '社会文化',
}

# 罕见 PDF 字距拆行词头手动修正
WORD_FIX = {
    'mus hro om': 'mushroom',
    'ma sh': 'mash',
    'com memora te': 'commemorate',
    'w a r m': 'warm',
    'd a m p': 'damp',
    'engagemen': 'engagement',
}


def band_of(word: str) -> str:
    n = len(word.replace(' ', '').replace('-', ''))
    if n >= 12:
        return 'Band 7.5'
    if n >= 9:
        return 'Band 7.0'
    if n >= 6:
        return 'Band 6.5'
    return 'Band 6.0'


def esc(s: str) -> str:
    return s.replace('\\', '\\\\').replace("'", "\\'")


def clean(s: str) -> str:
    # 符号清理 + 全角括号归一
    for ch in ('•', '□', '■', '●', '\uf0a3', '\uf0a7'):
        s = s.replace(ch, '')
    s = s.replace('［', '[').replace('］', ']').replace('（', '(').replace('）', ')')
    s = s.replace('；', ';').replace('，', ',').replace('、', ',')
    import re
    s = re.sub(r'\s{2,}', ' ', s).strip(' ;,/')
    return s


def main():
    data = json.loads(RAW.read_text(encoding='utf-8'))
    lines = [
        '// AUTO-GENERATED by scripts/gen_zhenjing_ts.py from 《雅思词汇真经》词汇表List.pdf',
        '// 雅思词汇真经（刘洪波）真实词库 — 21 主题分类，与 OFFLINE_LEXICON 同构。',
        '// 作为精选词库之后的第二优先级层，扩充雅思真题词库覆盖面。',
        '',
        "import type { WordItem } from '../types/dictionary';",
        '',
        'export interface ZhenjingLexEntry {',
        '  pos: string;',
        '  translation: string;',
        '  englishDefinition: string;',
        '  ieltsBand: string;',
        "  topic: '环境生态' | '科技媒体' | '学术教育' | '社会文化' | '经济工作' | '政府法律' | '心理生活';",
        '  examContextTag: string;',
        '  example: string;',
        '  exampleTranslation: string;',
        '  collocations: string[];',
        '  synonyms: string[];',
        '}',
        '',
        'export const IELTS_ZHENJING_LEXICON: Record<string, ZhenjingLexEntry> = {',
    ]
    n = 0
    for e in data:
        word = WORD_FIX.get(e['word'], e['word'])
        if not word or not word.replace(' ', '').replace('-', '').isalpha():
            continue
        zh = clean(e['zh'])
        if not zh:
            continue
        topic = TOPIC_MAP.get(e['topic'], '社会文化')
        pos = clean(e.get('pos', ''))
        ph = clean(e.get('phonetic', ''))
        tag = f"雅思词汇真经 · {e['topic']}"
        lines.append(
            f"  '{esc(word.lower())}': {{ pos: '{esc(pos)}', translation: '{esc(zh)}', "
            f"englishDefinition: '', ieltsBand: '{band_of(word)}', topic: '{topic}', "
            f"examContextTag: '{esc(tag)}', example: '', exampleTranslation: '', "
            f"collocations: [], synonyms: [] }},"
        )
        n += 1
    lines.append('};')
    lines.append('')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print('entries written:', n)
    print('saved:', OUT)


if __name__ == '__main__':
    main()
