#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""从 ECDICT(stardict.db) 生成补充词库 TS 模块。

只收「纯字母（可含连字符/撇号）」的单词，过滤超长词与空释义。
字段用 \\x01 分隔、条目用 \\n 分隔，尽量压缩体积：
    word \\x01 phonetic \\x01 pos \\x01 translation \\x01 exchange

- phonetic：ECDICT 旧式音标（运行时转 IPA）
- pos：形如 n:10/v:90，表示该词作为名词/动词的词频占比
- translation：中文释义（把 [网络] 前缀去掉）
- exchange：词形变化，形如 i:flirting/p:flirted/d:flirted/3:flirts/s:flirts
"""
import re
import sqlite3
import sys
from pathlib import Path

SRC = Path(r'D:\tmp_stardict.db')
OUT = Path(r'D:\ielts-lexicon\src\data\ecdictSupplement.ts')

WORD_RE = re.compile(r"^[a-zA-Z][a-zA-Z'\-]*$")
MAX_WORD = 25
MAX_TR = 110          # 中文释义截断长度
SEP = '\x01'


def clean_tr(s: str) -> str:
    s = s.replace('\r', '')
    # 去掉 [网络] / [计] 等前缀，换成简洁形式
    s = re.sub(r'^\[([^\]]{1,6})\]\s*', r'\1: ', s)
    # 换行→分号
    s = re.sub(r'\s*\n\s*', '；', s)
    # 折叠多余空白与重复分号
    s = re.sub(r'\s+', ' ', s)
    s = re.sub(r'[；;]{2,}', '；', s)
    s = s.strip(' ;；')
    return s[:MAX_TR]


def main():
    if not SRC.exists():
        print(f'缺少源数据库: {SRC}', file=sys.stderr)
        return 1

    con = sqlite3.connect(str(SRC))
    cur = con.cursor()

    rows = cur.execute(
        "SELECT word, phonetic, pos, translation, exchange, bnc, frq, collins, tag, oxford "
        "FROM stardict WHERE translation IS NOT NULL AND translation <> ''"
    )

    picked = []
    for w, ph, pos, tr, ex, bnc, frq, col, tag, ox in rows:
        if not WORD_RE.match(w) or len(w) > MAX_WORD:
            continue
        tr2 = clean_tr(tr or '')
        if not tr2 or len(tr2) < 2:
            continue
        strength = (10 if tag else 0) + (5 if (col or 0) > 0 else 0) + (10 if ox == 1 else 0) \
                 + (4 if (bnc or 0) > 0 else 0) + (4 if (frq or 0) > 0 else 0) \
                 + (6 if ex else 0) + (3 if ph else 0)
        picked.append((strength, w, (ph or '').strip(), (pos or '').strip(), tr2, (ex or '').strip()))

    # 按质量降序，仅在体积超限时截断
    picked.sort(key=lambda r: (-r[0], len(r[1])))

    # 去重（同名只留第一条）
    seen = set()
    uniq = []
    for p in picked:
        if p[1] in seen:
            continue
        seen.add(p[1])
        uniq.append(p)

    # ---- 剔除「是另一个词条的屈折形式」的条目 ----
    # 这些词前端已能用规则还原（flirting → flirt），不必占体积。
    all_words = {p[1].lower() for p in uniq}

    def inflect_base(w: str):
        """返回 w 可能的原形列表"""
        w = w.lower()
        out = []
        for suf, note in (('ings', ''), ('ing', ''), ('ied', 'y'), ('ed', ''), ('ies', 'y'),
                          ('es', ''), ('s', ''), ('er', ''), ('est', ''), ('ly', '')):
            if not w.endswith(suf) or len(w) <= len(suf) + 2:
                continue
            stem = w[:-len(suf)]
            if note == 'y':
                out.append(stem + 'y')
            out.append(stem)
            out.append(stem + 'e')
            if len(stem) >= 3 and stem[-1] == stem[-2]:
                out.append(stem[:-1])
        return out

    kept = []
    dropped_infl = 0
    for p in uniq:
        w = p[1]
        # 只有当原形词条本身质量更高（在词库里存在）时才丢掉屈折形式
        bases = [b for b in inflect_base(w) if b != w.lower() and b in all_words]
        if bases:
            dropped_infl += 1
            continue
        kept.append(p)

    uniq = kept
    print(f'剔除屈折形式 {dropped_infl} 条，剩余 {len(uniq)} 条')

    # ---- 体积预算控制 ----
    # 高置信（有音标 / 有词形变化 / 有词性占比）全量保留；
    # 弱词条（仅网络释义）按释义质量补足到预算内，避免打包出一份下不动的词库。
    BYTE_BUDGET = 11 * 1024 * 1024   # UTF-8 字节预算（中文占 3 字节），约合 6MB gzip

    def blen(s: str) -> int:
        return len(s.encode('utf-8'))

    def is_strong(p):
        return bool(p[2]) or bool(p[5]) or bool(p[3])

    def weak_rank(p):
        tr = p[4]
        # 释义越像正经词典（含词性标记或分号分项）越优先，其次越短越好
        marker = 2 if re.search(r'(?:^|；|\s)(?:n|vt|vi|adj|adv|prep|conj|pron)\.', tr) else 0
        detail = 1 if ('；' in tr or '，' in tr) else 0
        return (-(marker + detail), len(p[1]))

    strong_list = [p for p in uniq if is_strong(p)]
    weak_list = sorted([p for p in uniq if not is_strong(p)], key=weak_rank)

    chosen = list(strong_list)
    used = sum(blen(SEP.join([p[1], p[2], p[3], p[4], p[5]])) + 1 for p in chosen)
    for p in weak_list:
        sz = blen(SEP.join([p[1], p[2], p[3], p[4], p[5]])) + 1
        if used + sz > BYTE_BUDGET:
            break
        chosen.append(p)
        used += sz

    print(f'高置信 {len(strong_list)} 条 + 弱词条 {len(chosen) - len(strong_list)} 条 = {len(chosen)} 条，'
          f'约 {used / 1024 / 1024:.1f} MB (utf8)')
    uniq = chosen

    lines = [SEP.join([p[1], p[2], p[3], p[4], p[5]]) for p in uniq]
    payload = '\n'.join(lines)

    header = (
        '// AUTO-GENERATED by scripts/gen_ecdict_supplement.py from ECDICT (stardict.db).\n'
        '// 补充词库：牛津词库未收录的词（生僻词、文学词、外来词等）从这里兜底。\n'
        '// 格式：word\\x01 phonetic\\x01 pos(如 n:10/v:90)\\x01 中文释义 \\x01 词形变化，条目间以 \\n 分隔。\n'
        '// 数据来源：ECDICT https://github.com/skywind3000/ECDICT （MIT License）\n\n'
        'export const ECDICT_SUPPLEMENT_RAW: string =\n'
    )

    # 用单引号 JS 字符串，转义反斜杠、单引号与换行（换行必须转义，否则字符串字面量非法）
    def esc(s: str) -> str:
        return (s.replace('\\', '\\\\')
                 .replace("'", "\\'")
                 .replace('\r', '')
                 .replace('\n', '\\n'))

    chunks = []
    CH = 60000
    for i in range(0, len(payload), CH):
        chunks.append("  '" + esc(payload[i:i + CH]) + "'")

    body = ' +\n'.join(chunks) + ';\n\n'
    body += '/** 补充词库词条数 */\n'
    body += f'export const ECDICT_SUPPLEMENT_COUNT = {len(uniq)};\n'

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + body, encoding='utf-8')

    size_mb = OUT.stat().st_size / 1024 / 1024
    print(f'已生成 {OUT}')
    print(f'词条数 {len(uniq)}，文件 {size_mb:.1f} MB')
    return 0


if __name__ == '__main__':
    sys.exit(main())